import express from 'express';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import eventHandler from './api/event.js';
import passHandler from './api/pass.js';
import verifyHandler from './api/verify.js';

const dir=path.dirname(fileURLToPath(import.meta.url));
const app=express();
app.disable('x-powered-by');
app.use(express.json({limit:'3kb'}));
app.use((req,res,next)=>{res.setHeader('X-Content-Type-Options','nosniff');res.setHeader('Referrer-Policy','no-referrer');next()});
app.get(['/','/induction','/induction/'],(req,res)=>res.sendFile(path.join(dir,'index.html')));
app.get(['/verify','/verify/'],(req,res)=>res.sendFile(path.join(dir,'verify.html')));
app.get('/api/event',eventHandler);
app.get('/api/verify',verifyHandler);
app.post('/api/pass',(req,res)=>Promise.resolve(passHandler(req,res)).catch(()=>{if(!res.headersSent)res.status(500).json({error:'Pass service unavailable.'})}));
app.get('/healthz',(req,res)=>res.json({ok:true,service:'aristoverse-induction'}));
app.use((req,res)=>res.status(404).send('Not found'));
const port=Number(process.env.PORT)||3000;
app.listen(port,'0.0.0.0',()=>console.log('Aristoverse induction listening on port '+port));